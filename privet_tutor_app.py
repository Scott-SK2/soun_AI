def rag_tutor_step(history, k: int = 4, max_tokens: int = 360, temperature: float = 0.2):
    # Use last user message as retrieval query
    last_user = next((m["content"] for m in reversed(history) if m["role"] == "user"), "")
    retrieved = retrieve(last_user, k=k)

    context_blocks = []
    for r in retrieved:
        context_blocks.append(f"[{r['id']}] {r['text']}")
    context = "\n\n".join(context_blocks)

    prompt = (
        f"{RAG_SYSTEM}\n\n"
        f"CONTEXT:\n{context}\n\n"
        f"CONVERSATION:\n{format_history_for_rag(history)}\n\n"
        f"Tutor:"
    )

    out = llm(prompt, max_tokens=max_tokens, temperature=temperature, top_p=0.9, stop=["User:"])
    text = out["choices"][0]["text"].strip()

    # Basic enforcement: ensure one Check and Sources line
    if "Check:" not in text:
        text = text.rstrip() + "\n\nCheck: What is one key idea from what we just covered?"
    if "Sources:" not in text:
        used = ", ".join([r["id"] for r in retrieved[:2]]) if retrieved else "None"
        text = text.rstrip() + f"\nSources: {used}"

    # Keep only last Check line
    last = text.rfind("Check:")
    before = text[:last].rstrip()
    check_line = text[last:].splitlines()[0].strip()
    # Keep Sources line if it exists after (or append it)
    sources_match = [ln for ln in text.splitlines() if ln.strip().startswith("Sources:")]
    sources_line = sources_match[-1].strip() if sources_match else "Sources: None"

    text = before + "\n\n" + check_line + "\n" + sources_line
    return text, retrieved

