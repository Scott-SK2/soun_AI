def tokenize(text: str) -> set:
    text = re.sub(r"[^a-zA-Z0-9\s]", " ", text.lower())
    return {w for w in text.split() if len(w) >= 3}

QUESTION_STARTERS = ("why","what","who","how","when","where","which","can","could","should","is","are","do","does","was","were")

def looks_like_question(student: str) -> bool:
    s = student.strip().lower()
    return s.endswith("?") or s.startswith(QUESTION_STARTERS)

def relatedness(a: str, b: str) -> float:
    A, B = tokenize(a), tokenize(b)
    if not A or not B:
        return 0.0
    return len(A & B) / len(A | B)

def extract_last_check(history: List[Dict[str, str]]) -> Optional[str]:
    last = next((m["content"] for m in reversed(history) if m["role"] == "assistant"), None)
    if not last:
        return None
    idx = last.rfind("Check:")
    if idx == -1:
        return None
    return last[idx:].splitlines()[0].strip()

