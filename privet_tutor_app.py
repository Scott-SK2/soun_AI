CONFUSION_PATTERNS = [
    r"\bi( do not| don't)? understand\b",
    r"\bconfus(ed|ing)\b",
    r"\bcan you explain (again|more)\b",
    r"\bthat (didn't|did not) make sense\b",
    r"\bwhat do you mean\b",
]

def is_confused(s: str) -> bool:
    t = s.strip().lower()
    return any(re.search(p, t) for p in CONFUSION_PATTERNS)

def diagnose_gaps(history: List[Dict[str, str]]) -> Dict[str, str]:
    """
    Uses the model to summarize what the student seems to know and where the gaps are,
    based on conversation so far.
    """
    analyst = (
        "You are an expert tutor analyzing a student's understanding.\n"
        "Return exactly three labeled lines:\n"
        "Known: <what they seem to understand>\n"
        "Gaps: <what is missing or incorrect>\n"
        "Focus: <what to explain next (short)>\n"
    )
    transcript = []
    for m in history[-10:]:
        role = "Student" if m["role"] == "user" else "Tutor"
        transcript.append(f"{role}: {m['content']}")
    prompt = analyst + "\n\n" + "\n".join(transcript) + "\n"
    out = llm(prompt, max_tokens=120, temperature=0.2, top_p=0.9, stop=["\n\n"])
    text = out["choices"][0]["text"].strip()

    known = re.search(r"Known:\s*(.*)", text)
    gaps = re.search(r"Gaps:\s*(.*)", text)
    focus = re.search(r"Focus:\s*(.*)", text)
    return {
        "Known": known.group(1).strip() if known else "",
        "Gaps": gaps.group(1).strip() if gaps else "",
        "Focus": focus.group(1).strip() if focus else "",
        "raw": text
    }

def targeted_explain(topic: str, known: str, gaps: str, focus: str) -> str:
    tutor = (
        "You are a strict but helpful tutor.\n"
        "Explain ONLY what is missing/unclear (the gaps). Do not repeat what the student already knows.\n"
        "Use 2–6 sentences. Optionally include ONE short example appropriate to the student.\n"
        "End with exactly ONE 'Check:' line that tests the gap you just explained.\n"
    )
    prompt = (
        f"{tutor}\n\nTopic: {topic}\nKnown: {known}\nGaps: {gaps}\nFocus: {focus}\n\nTutor:\n"
    )
    out = llm(prompt, max_tokens=260, temperature=0.2, top_p=0.9, stop=["User:"])
    return clean_to_single_check(out["choices"][0]["text"].strip())

