def extract_last_check_from_text(tutor_text: str) -> Optional[str]:
    idx = tutor_text.rfind("Check:")
    if idx == -1:
        return None
    return tutor_text[idx:].splitlines()[0].strip()

def extract_last_tutor_msg(history: List[Dict[str, str]]) -> Optional[str]:
    for m in reversed(history):
        if m["role"] == "assistant":
            return m["content"]
    return None

def is_idk(s: str) -> bool:
    s = s.strip().lower()
    return s in {"i dont know", "i don't know", "idk", "dont know", "don't know", "no idea", "??", "?"}

def is_greeting(s: str) -> bool:
    s = s.strip().lower()
    return s in {"hello", "hi", "hey", "yo", "sup", "wag1", "wagwan"}

def tokenize(text: str) -> set:
    text = re.sub(r"[^a-zA-Z0-9\s]", " ", text.lower())
    return {w for w in text.split() if len(w) >= 3}

QUESTION_STARTERS = (
    "why", "what", "who", "how", "when", "where",
    "which", "can", "could", "should", "is", "are", "do", "does", "was", "were"
)

def looks_like_question(student: str) -> bool:
    s = student.strip().lower()
    return s.endswith("?") or s.startswith(QUESTION_STARTERS)

def relatedness(a: str, b: str) -> float:
    A = tokenize(a)
    B = tokenize(b)
    if not A or not B:
        return 0.0
    return len(A & B) / len(A | B)

