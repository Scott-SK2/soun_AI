def safe_tutor_step(history: List[Dict[str, str]]) -> str:
    """
    Ensures we get:
    - at least some teaching content
    - exactly one Check at the end
    If the tutor outputs only a Check, regenerate once.
    """
    msg = tutor_chat_step(history).strip()
    msg = clean_to_single_check(msg)

    # If message has no teaching content (only Check line), regenerate once
    only_check = re.fullmatch(r"(?s)\s*Check:.*", msg.strip()) is not None
    if only_check:
        regen_instruction = (
            "Tutor: Your last output contained only a Check question. "
            "Provide ONE short teaching chunk first (2-5 sentences), THEN one 'Check:' question."
        )
        tmp_history = history + [{"role": "user", "content": regen_instruction}]
        msg = tutor_chat_step(tmp_history).strip()
        msg = clean_to_single_check(msg)

    return msg

